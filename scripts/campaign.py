"""Run a campaign: a committed list of runs, several at a time, resumable.

A campaign file (``campaigns/<name>.txt``, generated by
``scripts/make_campaign.py`` and committed with the code) holds one run per line:

    <run-name> <arguments of scripts/run_cil.py, without --run-dir>

Each run writes ``<out-root>/<run-name>/``; a run whose ``metrics.json`` exists
is skipped, so a resubmitted job only does what is left. ``--shard i/n`` takes
every n-th line starting at i (0-based), to spread a campaign over n jobs.

    python scripts/campaign.py campaigns/pilot.txt --parallel 8 --threads 4 --shard 0/2
"""

from __future__ import annotations

import argparse
import os
import shlex
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def read_campaign(path: Path):
    runs = []
    for line in path.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        name, *rest = shlex.split(line)
        runs.append((name, rest))
    names = [n for n, _ in runs]
    if len(names) != len(set(names)):
        raise ValueError(f"{path}: duplicate run names")
    return runs


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("campaign")
    p.add_argument("--out-root", default="out/runs")
    p.add_argument("--parallel", type=int, default=1)
    p.add_argument("--threads", type=int, default=4)
    p.add_argument("--shard", default="0/1")
    p.add_argument("--dry-run", action="store_true")
    args = p.parse_args(argv)

    i, n = (int(x) for x in args.shard.split("/"))
    runs = read_campaign(Path(args.campaign))[i::n]
    out_root = Path(args.out_root)
    todo = [(name, rest) for name, rest in runs if not (out_root / name / "metrics.json").exists()]
    print(f"{args.campaign} shard {args.shard}: {len(runs)} runs, {len(todo)} to do", flush=True)
    if args.dry_run:
        for name, rest in todo:
            print(name, " ".join(rest))
        return 0

    py = sys.executable
    running: list[tuple[str, subprocess.Popen, float]] = []
    failed = []
    queue = list(todo)
    while queue or running:
        while queue and len(running) < args.parallel:
            name, rest = queue.pop(0)
            run_dir = out_root / name
            run_dir.mkdir(parents=True, exist_ok=True)
            cmd = [py, str(ROOT / "scripts" / "run_cil.py"), *rest,
                   "--run-dir", str(run_dir), "--threads", str(args.threads)]
            log = open(run_dir / "stdout.log", "w")
            log.write(" ".join(shlex.quote(c) for c in cmd) + "\n")
            log.flush()
            proc = subprocess.Popen(cmd, stdout=log, stderr=subprocess.STDOUT, cwd=ROOT, env=os.environ.copy())
            running.append((name, proc, time.time()))
            print(f"start {name}", flush=True)
        time.sleep(5)
        still = []
        for name, proc, t0 in running:
            rc = proc.poll()
            if rc is None:
                still.append((name, proc, t0))
                continue
            ok = rc == 0 and (out_root / name / "metrics.json").exists()
            print(f"{'done' if ok else 'FAIL'} {name} rc={rc} {time.time() - t0:.0f}s", flush=True)
            if not ok:
                failed.append(name)
        running = still
    print(f"finished: {len(todo) - len(failed)} ok, {len(failed)} failed {failed}", flush=True)
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
